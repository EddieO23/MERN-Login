const UserModel = require('../models/UserModel');
const otp_generator = require('otp-generator');
const bcrypt = require('bcrypt');
const jwt = require('jsonwebtoken');

const sendEmail = require('../email_service/Email');

const register = async (req, res) => {
  try {
    // console.log(req.body);

    const isUserExisting = await UserModel.findOne({ email: req.body.email });

    if (isUserExisting) {
      console.log('User already exists.');
      return res
        .status(400)
        .json({ msg: `User with ${req.body.email} already exists` });
    }

    const verificationToken = otp_generator.generate(6, {
      upperCaseAlphabets: false,
      specialChars: false,
    });

    const expires = new Date();

    expires.setMinutes(expires.getMinutes() + 5);

    const hashedPassword = await bcrypt.hash(req.body.password, 10);

    const newUser = await UserModel({
      email: req.body.email,
      username: req.body.username,
      password: hashedPassword,
      verificationToken: {
        token: verificationToken,
        expires: expires,
      },
    });

    console.log(newUser);

    await newUser.save();

    const emailBody = `<p>Please click on the link to verify your account. <b>http://localhost:4000/user/verify/${verificationToken}</b></p>`;

    const subject = 'Please Verify Your Account';

    await sendEmail(req.body.email, subject, emailBody);

    res.json({ msg: 'Verification link sent to your email.' });
  } catch (error) {
    res.json({ msg: 'Something went wrong.' });
  }
};

const login = async (req, res) => {
  try {
    const isUserExisting = await UserModel.findOne({ email: req.body.email });

    // console.log(isUserExisting);

    const password = otp_generator.generate(12, {
      upperCaseAlphabets: true,
      lowerCaseAlphabets: true,
      digits: true,
      specialChars: true,
    });

    const hashedPassword = await bcrypt.hash(password, 10);

    if (!isUserExisting) {
      if (req.body.autoGenerated) {
        const newUser = await UserModel({
          email: req.body.email,
          username: req.body.username,
          password: hashedPassword,
          isVerified: true,
        });

        await newUser.save();

        const jwtPayload = {
          id: newUser._id,
        };

        const token = jwt.sign(jwtPayload, process.env.SECRET, {
          expiresIn: '1h',
        });

        const emailBody = `<p>Account created successfully! Your password is <b>${password}</b>.Please change it.</p>`;

        const subject = 'Account created VIA Social.';

        await sendEmail(req.body.email, subject, emailBody);

        return res.status(200).json({ msg: 'Logged in via social.', token });
      }

      return res
        .status(400)
        .json({ msg: `User with ${req.body.email} does not exist` });
    }

    if (!isUserExisting.isVerified) {
      return res.status(400).json({
        msg: `User is not verified. Please click the link in your email to verify.`,
      });
    }

    const isPasswordCorrect = await bcrypt.compare(
      req.body.password,
      isUserExisting.password
    );

    if (!isPasswordCorrect) {
      return res.status(400).json({ msg: 'Invalid credentials' });
    }

    // Create a JWT

    const jwtPayload = {
      id: isUserExisting._id,
    };

    const token = jwt.sign(jwtPayload, process.env.SECRET, {
      expiresIn: '1h',
    });

    res.json({ msg: 'Welcome.', token });
  } catch (error) {
    res
      .status(500)
      .json({ msg: 'Something went wrong when trying to log in.' });
  }
};

const verifyUser = async (req, res) => {
  try {
    const { token } = req.params;

    const isTokenValid = await UserModel.findOne({
      'verificationToken.token': token,
      'verificationToken.expires': { $gt: new Date() },
    });

    if (!isTokenValid) {
      return res.send(
        `<p>Token invalid or expired.</p><a href="http://localhost:4000/user/resendVerification/${token}">Resend Verification Email</a>`
      );
    }

    if (isTokenValid.isVerified) {
      res.send('<p>Account is already verified. Please log in.</p>');
    }

    isTokenValid.isVerified = true;

    await isTokenValid.save();

    res.send('Your account is verified!');
  } catch (error) {
    console.log(error);
  }
};

const resendVerification = async (req, res) => {
  try {
    const { token } = req.params;

    const user = await UserModel.findOne({
      'verificationToken.token': token,
      isVerified: false,
    });

    if (!user) {
      return res.send('User not found or already verified.');
    }

    const verificationToken = otp_generator.generate(6, {
      upperCaseAlphabets: false,
      specialChars: false,
    });

    const expires = new Date();

    expires.setMinutes(expires.getMinutes() + 3);

    user.verificationToken = {
      expires: expires,
      token: verificationToken,
    };

    await user.save();

    // Send email

    const emailBody = `<p>Please click on the link to verify your account. <b>http://localhost:4000/user/verify/${verificationToken}</b></p>`;

    const subject = 'Verificaiton Email';

    await sendEmail(user.email, subject, emailBody);

    res.send('Please check your email for a new verification link.');
  } catch (error) {
    console.error(error);

    res.send('Something went wrong.');
  }
};

