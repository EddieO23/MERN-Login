const forgotPassword = async (req, res) => {
  try {
    console.log(req.body);

    const isUserExisting = await UserModel.findOne({ email: req.body.email });

    if (!isUserExisting) {
      return res
        .status(400)
        .json({ msg: `User with ${req.body.email} doesn't exists.` });
    }

    if (req.body.isOTPVerified) {
      const hashedPassword = await bcrypt.hash(req.body.password, 10);

      isUserExisting.password = hashedPassword;

      await isUserExisting.save();

      const emailBody = `<p>Your password was reset was successful.`;

      const subject = 'Password Reset Successfully';

      await sendEmail(isUserExisting.email, subject, emailBody);

      return res.status(200).json({ msg: 'Password Reset Successfully.' });
    }

    const OTP = otp_generator.generate(6, {
      upperCaseAlphabets: false,
      specialChars: false,
    });

    const expires = new Date();

    expires.setMinutes(expires.getMinutes() + 5);

    isUserExisting.OTP_VerificationToken = {
      OTP,
      expires,
    };

    await isUserExisting.save();

    const emailBody = `<p>Your OTP for passoword reset request is <b>${OTP}</b> <br> OTP expires in 5 mins</p>`;

    const subject = 'Reset Your Password';

    await sendEmail(isUserExisting.email, subject, emailBody);

    res.status(200).json({ msg: 'OTP Sent Successfully.' });
  } catch (error) {
    console.log(error);

    res.status(500).json({ msg: `Something went wrong.` });
  }
};

